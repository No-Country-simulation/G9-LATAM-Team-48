export function getUiExtendedPatch(code) {
  if (code === 'es' || code === 'en') return {}

  const filters = FILTERS[code]
  if (!filters) return {}

  const patch = {
    chart: { filters },
    historiaConsumos: {
      filterPeriod: filters.period,
      ...HISTORIA[code],
    },
  }

  if (DASHBOARD[code]) {
    patch.dashboard = DASHBOARD[code]
  }

  return patch
}
