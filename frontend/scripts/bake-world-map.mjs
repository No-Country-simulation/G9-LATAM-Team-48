import { createRequire } from 'module'
import { writeFileSync } from 'fs'
import { geoEquirectangular, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)
const countriesTopo = require('world-atlas/countries-110m.json')

const WIDTH = 1000
const HEIGHT = 500

/**
 * Natural Earth country names → locale code of the app.
 * Varios países pueden compartir el mismo idioma.
 */
const NAME_TO_LOCALE = {
  // Español
  Spain: 'es',
  Mexico: 'es',
  Argentina: 'es',
  Colombia: 'es',
  Chile: 'es',
  Peru: 'es',
  Uruguay: 'es',
  Paraguay: 'es',
  Bolivia: 'es',
  Ecuador: 'es',
  Venezuela: 'es',
  Guatemala: 'es',
  Honduras: 'es',
  'El Salvador': 'es',
  Nicaragua: 'es',
  'Costa Rica': 'es',
  Panama: 'es',
  Cuba: 'es',
  'Dominican Rep.': 'es',
  'Eq. Guinea': 'es',

  // Portugués
  Portugal: 'pt',
  Brazil: 'pt',
  Angola: 'pt',
  Mozambique: 'pt',

  // Inglés
  'United States of America': 'en',
  'United Kingdom': 'en',
  Ireland: 'en',
  Canada: 'en',
  Australia: 'en',
  'New Zealand': 'en',
  Jamaica: 'en',
  'South Africa': 'en',

  // Francés
  France: 'fr',
  Belgium: 'fr',
  Luxembourg: 'fr',
  Monaco: 'fr',
  Senegal: 'fr',
  'Côte d\'Ivoire': 'fr',
  Morocco: 'fr',
  Algeria: 'fr',
  Tunisia: 'fr',

  // Italiano
  Italy: 'it',
  'San Marino': 'it',

  // Alemán
  Germany: 'de',
  Austria: 'de',
  Liechtenstein: 'de',

  // Neerlandés
  Netherlands: 'nl',
  Suriname: 'nl',

  // Polaco
  Poland: 'pl',

  // Rumano
  Romania: 'ro',
  Moldova: 'ro',

  // Turco
  Turkey: 'tr',

  // Catalán (Andorra; Catalunya no es país en este mapa)
  Andorra: 'ca',
}

const projection = geoEquirectangular()
  .fitSize([WIDTH, HEIGHT], { type: 'Sphere' })
  .precision(0.5)

const path = geoPath(projection)
const collection = feature(countriesTopo, countriesTopo.objects.countries)

const countries = []
const unknownNames = []

for (const f of collection.features) {
  const name = f.properties?.name || 'Unknown'
  const d = path(f)
  if (!d) continue

  const locale = NAME_TO_LOCALE[name] || null
  if (!NAME_TO_LOCALE[name] && name !== 'Antarctica') {
    // keep quiet; useful when debugging missing names
  }

  countries.push({
    id: String(f.id ?? name),
    name,
    locale,
    d,
  })
}

// Centroides aproximados para etiquetas de idioma (un pin por locale)
const LOCALE_FOCUS = {
  es: [-64, -34],
  pt: [-47, -15],
  en: [-95, 38],
  ca: [1.5, 42.5],
  fr: [2.3, 46.6],
  nl: [5.3, 52.1],
  de: [10.5, 51.2],
  it: [12.5, 41.9],
  pl: [19.1, 52.2],
  ro: [26.1, 45.9],
  tr: [32.8, 39.9],
}

const markers = Object.entries(LOCALE_FOCUS).map(([code, [lon, lat]]) => {
  const [x, y] = projection([lon, lat])
  return {
    code,
    x: Math.round(x * 10) / 10,
    y: Math.round(y * 10) / 10,
  }
})

const byLocale = {}
for (const c of countries) {
  if (!c.locale) continue
  byLocale[c.locale] = (byLocale[c.locale] || 0) + 1
}

const js = `/* Auto-generated by scripts/bake-world-map.mjs — do not edit by hand. */
export const WORLD_MAP_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}'

export const WORLD_COUNTRIES = ${JSON.stringify(countries)}

export const LOCALE_MAP_MARKERS = ${JSON.stringify(markers, null, 2)}
`

writeFileSync(new URL('../src/data/worldMap.js', import.meta.url), js)

console.log('Wrote src/data/worldMap.js')
console.log('Countries:', countries.length)
console.log('Mapped by locale:', byLocale)
console.log(
  'Unmapped sample:',
  countries
    .filter((c) => !c.locale && c.name !== 'Antarctica')
    .slice(0, 15)
    .map((c) => c.name),
)
