function deepMerge(a, b) {
  const out = { ...a }
  for (const key of Object.keys(b || {})) {
    out[key] =
      b[key] && typeof b[key] === 'object' && !Array.isArray(b[key])
        ? deepMerge(a[key] || {}, b[key])
        : b[key]
  }
  return out
}

